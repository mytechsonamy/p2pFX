export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function createTranslator(locale: string, overrides: Record<string, string> = {}): Translate {
  const dict: Record<string, string> = { ...tr, ...(locale.startsWith('en') ? en : {}), ...overrides };
  return (key, vars) => {
    const s = dict[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

